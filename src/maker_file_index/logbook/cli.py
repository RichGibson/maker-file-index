"""laser-log: build Markdown day pages of laser use."""

from __future__ import annotations

import argparse
import hashlib
from datetime import date, timedelta
from pathlib import Path

from maker_file_index.logbook.daypage import GENERATED_MARK, merge_notes, render_day, unsafe_to_merge
from maker_file_index.logbook.debuglog import read_stream_jobs
from maker_file_index.logbook.index import day_note_summary, render_index
from maker_file_index.logbook.jobs import jobs_by_day, read_jobs
from maker_file_index.logbook.projectfile import version_at
from maker_file_index.logbook.store import load_stored, save_stream_job

DOCS = Path.home() / "Documents"


def _build(args: argparse.Namespace) -> int:
    log_dir = Path(args.log_dir).expanduser()
    for job in read_stream_jobs(Path(args.debug_log).expanduser()):
        save_stream_job(log_dir, job)

    by_day = jobs_by_day(read_jobs(Path(args.jobs_csv).expanduser()))
    if args.all:
        days = sorted(by_day)
    elif args.day:
        days = [date.fromisoformat(args.day)]
    else:
        # yesterday too: late jobs' log batches can flush after midnight
        days = [date.today() - timedelta(days=1), date.today()]

    wrote = skipped = 0
    log_dir.mkdir(parents=True, exist_ok=True)
    for day in days:
        jobs = by_day.get(day, [])
        if not jobs:
            continue
        page = log_dir / f"{day.isoformat()}.md"
        generated = render_day(day, jobs, load_stored(log_dir, day), version_at,
                               save_thumb=lambda png: _save_thumb(log_dir, png))
        if page.exists():
            existing = page.read_text()
            if not existing.startswith(GENERATED_MARK):
                print(f"skipped {page}: not generated by laser-log")
                skipped += 1
                continue
            problem = unsafe_to_merge(existing)
            if problem:
                print(f"skipped {page}: {problem}; fix it by hand, nothing was changed")
                skipped += 1
                continue
            generated = merge_notes(existing, generated)
            if generated == existing:
                continue
        page.write_text(generated)
        wrote += 1
    print(f"wrote {wrote} pages, skipped {skipped}")
    _write_index(log_dir, by_day)
    return 0


def _save_thumb(log_dir: Path, png: bytes) -> str:
    """Store a project thumbnail once, named by content, and return its page-relative path."""
    name = f"{hashlib.sha1(png).hexdigest()[:12]}.png"
    path = log_dir / "images" / "thumbs" / name
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(png)
    return f"images/thumbs/{name}"


def _write_index(log_dir: Path, by_day: dict) -> None:
    notes = {}
    for day in by_day:
        page = log_dir / f"{day.isoformat()}.md"
        if page.exists():
            summary = day_note_summary(page.read_text())
            if summary:
                notes[day] = summary
    index = log_dir / "index.md"
    if index.exists() and not index.read_text().startswith(GENERATED_MARK):
        print(f"skipped {index}: not generated by laser-log")
        return
    text = render_index(by_day, {d: load_stored(log_dir, d) for d in by_day}, notes)
    if not index.exists() or index.read_text() != text:
        index.write_text(text)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="laser-log", description="Build a Markdown logbook of laser jobs.")
    sub = parser.add_subparsers(dest="command", required=True)
    build = sub.add_parser("build", help="decode jobs and write day pages")
    build.add_argument("--log-dir", required=True, help="where day pages and job records live")
    build.add_argument("--jobs-csv", default=str(DOCS / "LightBurnJobs.csv"))
    build.add_argument("--debug-log", default=str(DOCS / "LightBurnLog.txt"))
    when = build.add_mutually_exclusive_group()
    when.add_argument("--day", help="YYYY-MM-DD (default: today)")
    when.add_argument("--all", action="store_true", help="every day in the job history")
    args = parser.parse_args(argv)
    return _build(args)


if __name__ == "__main__":
    raise SystemExit(main())
